"""
Phase 4: build the curated sample gallery for the Identify page.

Takes the Wikimedia Commons lead photo of selected knowledge-base entries
(data/species_kb.json, licence + author already recorded there), downsizes it
to at most 640 px on the long side, and writes:

  frontend/public/samples/<slug>.jpg     (small JPEGs, committed)
  frontend/src/lib/samples.json          (label, file, size, attribution)

Only openly licensed Commons images are used (never Open Images test crops).
Uses the offline cache from scripts/cache_species_images.py when present,
otherwise downloads the 960 px Commons thumbnail (generic User-Agent).

Usage (from the repo root):
    backend/.venv/bin/python scripts/make_samples.py
"""
from __future__ import annotations

import io
import json
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parent))
from cache_species_images import OUT_DIR as CACHE_DIR, fetch, thumb_url  # noqa: E402

KB_PATH = ROOT / "data" / "species_kb.json"
OUT_IMG = ROOT / "frontend" / "public" / "samples"
OUT_JSON = ROOT / "frontend" / "src" / "lib" / "samples.json"
MAX_SIDE = 640
QUALITY = 82

# Single, clearly visible animals across groups; chosen so the photo shows one subject.
SLUGS = [
    "red-panda", "cheetah", "tiger", "zebra", "koala", "fox",
    "owl", "crocodile", "ladybug", "goldfish", "crab", "jellyfish",
]


def source_bytes(e: dict) -> bytes:
    for ext in ("jpg", "png"):
        p = CACHE_DIR / f"{e['slug']}-hero.{ext}"
        if p.exists():
            return p.read_bytes()
    img = e["image"]
    return fetch(thumb_url(img["url"], 960, img.get("width")), delay=1.0)  # polite, honours Retry-After


def main() -> None:
    kb = {e["slug"]: e for e in json.loads(KB_PATH.read_text(encoding="utf-8"))["species"]}
    OUT_IMG.mkdir(parents=True, exist_ok=True)
    samples, total = [], 0
    for slug in SLUGS:
        e = kb[slug]
        im = Image.open(io.BytesIO(source_bytes(e))).convert("RGB")
        im.thumbnail((MAX_SIDE, MAX_SIDE), Image.LANCZOS)
        out = OUT_IMG / f"{slug}.jpg"
        im.save(out, "JPEG", quality=QUALITY, optimize=True, progressive=True)
        total += out.stat().st_size
        img = e["image"]
        samples.append({
            "slug": slug,
            "label": e["label"],
            "common_name": e["common_name"],
            "file": f"/samples/{slug}.jpg",
            "width": im.width,
            "height": im.height,
            "credit": {k: img.get(k) for k in ("artist", "license", "license_url", "source_url", "provider")},
        })
        print(f"{slug}: {im.width}x{im.height} {out.stat().st_size / 1024:.0f} KB ({img.get('license')})")
    OUT_JSON.write_text(json.dumps({
        "_note": "Generated by scripts/make_samples.py from data/species_kb.json (Wikimedia Commons, credited).",
        "samples": samples,
    }, indent=1, ensure_ascii=False) + "\n")
    print(f"{len(samples)} samples, {total / 1024:.0f} KB total -> {OUT_IMG.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
